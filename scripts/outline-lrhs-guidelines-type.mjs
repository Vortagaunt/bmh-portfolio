/**
 * The Industry Black lettering on the brand guidelines page
 * (/lrhs-brand-guidelines), outlined to SVG paths.
 *
 * Industry Black is licensed and never committed or served as a font. The
 * page only needs a handful of fixed phrases in it — the type specimen, the
 * scale, the three pillars and the rallying cries — so each phrase is set
 * once here, kerned, and saved as one finished path: artwork, the same way
 * the podcast badge and the lockups carry their lettering. There is no
 * per-letter glyph set in the output, so nothing here can be used as a font.
 *
 * Emits src/components/lrhs/guidelines/ib-type.ts. Re-run after changing
 * PHRASES (the page refers to them by the same text).
 *
 * Run: node scripts/outline-lrhs-guidelines-type.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const FONTS = [
  path.join(root, "public", "fonts", "industry-black.otf"),
  path.join(process.env.LOCALAPPDATA || "", "Microsoft", "Windows", "Fonts", "industry-black.otf"),
  path.join(root, "deck", "fonts", "industry-black.otf"),
];
const fontPath = FONTS.find((p) => p && fs.existsSync(p));
if (!fontPath) {
  console.error("Industry Black not found. Looked in:\n  " + FONTS.join("\n  "));
  process.exit(1);
}
const font = opentype.parse(fs.readFileSync(fontPath).buffer);
const UPM = font.unitsPerEm;

/* [phrase, tracking in em]. The alphabet and figures are spaced out like a
   specimen; everything else is set the way the guidelines ask for headlines,
   tight but tracked. GO and MUSTANGS are also set on their own so the
   specimen can colour them differently. */
const PHRASES = [
  ["GO", 0.01],
  ["MUSTANGS", 0.01],
  ["GO MUSTANGS", 0.01],
  ["ABCDEFGHIJKLMNOPQRSTUVWXYZ", 0.06],
  ["0123456789", 0.06],
  ["RIDE TOGETHER", 0.02],
  ["MUSTANG NEWS", 0.02],
  ["PROUD", 0.01],
  ["GROUNDED", 0.01],
  ["TOGETHER", 0.01],
  ["HOME OF THE MUSTANGS", 0.02],
  ["MUSTANG PRIDE", 0.02],
  ["ONE RANCH", 0.02],
  ["JOIN THE HERD", 0.02],
];

/* Cap height from the H, so every phrase shares one box: top of the capitals
   at y = -CAP, baseline at y = 0. */
const H = font.charToGlyph("H").getBoundingBox();
const CAP = Math.round(H.y2);

const out = {};
for (const [text, track] of PHRASES) {
  const glyphs = font.stringToGlyphs(text);
  let x = -glyphs[0].getBoundingBox().x1; // ink starts at x = 0
  const parts = [];
  let below = 0;
  glyphs.forEach((g, i) => {
    const p = g.getPath(x, 0, UPM);
    const d = p.toPathData(0);
    if (d) {
      parts.push(d);
      below = Math.max(below, Math.ceil(p.getBoundingBox().y2));
    }
    x += g.advanceWidth;
    if (i < glyphs.length - 1) x += font.getKerningValue(g, glyphs[i + 1]) + track * UPM;
  });
  /* trim the last letter's right side bearing so the box ends at the ink */
  const last = glyphs[glyphs.length - 1].getBoundingBox();
  const width = Math.round(x - glyphs[glyphs.length - 1].advanceWidth + last.x2);
  out[text] = { w: width, below, d: parts.join("") };
}

const file = path.join(root, "src", "components", "lrhs", "guidelines", "ib-type.ts");
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(
  file,
  `/* Generated by scripts/outline-lrhs-guidelines-type.mjs — do not edit by hand.
   Industry Black lettering as finished artwork (one path per phrase), so the
   licensed font is never shipped. Units: the font's own (${UPM} per em); every
   phrase sits on a baseline at y = 0 with capitals rising to y = -${CAP};
   \`below\` is how far any letter (the Q's tail) drops under it. */
export const IB_CAP = ${CAP};

export const IB = ${JSON.stringify(out, null, 2)} as const;

export type IbPhrase = keyof typeof IB;
`,
);
const bytes = fs.statSync(file).size;
console.log(`wrote ${path.relative(root, file)} — ${Object.keys(out).length} phrases, ${(bytes / 1024).toFixed(1)} KB`);
